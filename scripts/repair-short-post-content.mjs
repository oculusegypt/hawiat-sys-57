function expansionFor(post) {
  const topic = topicFor(post.title);
  const title = escapeHtml(post.title);
  return `${MARKER}
<h2>${topic.label}: كيف تطبق ما ورد في «${title}»؟</h2>
<p>${topic.intro} إذا كان موضوع «${title}» مرتبطاً بطلب قائم، استخدم الخطوات التالية كقائمة تجهيز قبل التواصل.</p>
<h2>قائمة تنفيذ مختصرة</h2>
<ol>${topic.steps.map((step) => `<li>${step}</li>`).join("")}</ol>
<h2>أخطاء ترفع الوقت أو التكلفة</h2>
<p>${topic.mistakes} كما أن ترك تفاصيل الوصول إلى يوم التنفيذ يجعل معالجة العوائق أصعب، لذلك من الأفضل إرسال البيانات والصور مبكراً.</p>
<h2>${topic.question}</h2>
<p>${topic.answer}</p>
<h2>الخلاصة</h2>
<p>ابدأ بالبيانات القابلة للتحقق، ثم طابق نوع الخدمة مع الموقع والمدة. عند تغير كمية المخلفات أو موعد المشروع، حدّث فريق العمليات بدلاً من الاستمرار على الخطة الأولى. بهذه الطريقة يصبح المقال مرجعاً عملياً لاتخاذ القرار، وليس مجرد تعريف عام بالخدمة.</p>`;
}

const dbPaths = [
  join(ROOT, "data", "sabaik.db"),
  join(ROOT, "build_php", "data", "sabaik.db"),
].filter(existsSync);

for (const dbPath of dbPaths) {
  const db = new Database(dbPath);
  const columns = db.prepare("PRAGMA table_info(posts)").all().map((column) => column.name);
  const hasUpdatedAt = columns.includes("updated_at");
  const update = db.prepare(`
    UPDATE posts
    SET content = @content${hasUpdatedAt ? ", updated_at = datetime('now')" : ""}
    WHERE id = @id AND status = 'published' AND is_active = 1
      AND length(trim(coalesce(content, ''))) < 1500
      AND instr(content, @marker) = 0
  `);
  const rows = db.prepare(`
    SELECT id, title, content
    FROM posts
    WHERE status = 'published' AND is_active = 1
      AND length(trim(coalesce(content, ''))) < 1500
  `).all();
  const run = db.transaction(() => {
    let changed = 0;
    for (const post of rows) {
      const content = `${String(post.content || "").trim()}${String(post.content || "").trim() ? "\n" : ""}${expansionFor(post)}`;
      changed += update.run({ id: post.id, content, marker: MARKER }).changes;
    }
    return changed;
  });
  const changed = run();
  const integrity = db.pragma("integrity_check", { simple: true });
  db.close();
  if (integrity !== "ok") throw new Error(`${dbPath}: SQLite integrity check failed: ${integrity}`);
  console.log(`✅ ${dbPath.replace(`${ROOT}/`, "")}: ${changed} مقالة قصيرة موسعة`);
}